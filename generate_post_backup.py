def query_notebooklm(topic: str, notebook_id: str) -> str:
    """Запрашивает NotebookLM и возвращает релевантный материал по теме."""
    import subprocess
    try:
        result = subprocess.run(
            ["notebooklm", "ask", f"Дай подробный материал по теме: {topic}. "
             f"Включи факты, механизмы, примеры — всё что поможет написать экспертный пост.",
             "--notebook", notebook_id],
            capture_output=True, text=True, timeout=180,
            env={**os.environ, "PATH": f"{os.path.expanduser('~/bin')}:{os.environ.get('PATH', '')}"}
        )
        if result.returncode == 0 and result.stdout.strip():
            return result.stdout.strip()
    except Exception as e:
        print(f"  [notebooklm] ошибка: {e}")
    return ""


def search_knowledge(topic: str, notebook_id: str = None) -> str:
    """Ищет материал — сначала в NotebookLM, потом в локальной базе."""

    # 1. Пробуем NotebookLM если указан ноутбук
    if notebook_id:
        print(f"  [NotebookLM] запрашиваю материал...")
        content = query_notebooklm(topic, notebook_id)
        if content:
            print(f"  [NotebookLM] получен материал ✓")
            return f"Материал из NotebookLM:\n\n{content}"

    # 2. Fallback на локальную базу
    try:
        from knowledge_base.kb_store import search, count
        if count() > 0:
            results = search(topic, n_results=5)
            if results:
                parts = [r["text"] for r in results]
                sources = list(dict.fromkeys(r["source"] for r in results))
                print(f"  [локальная база] найдены материалы ✓")
                return f"Материалы из базы знаний ({', '.join(sources)}):\n\n" + "\n\n---\n\n".join(parts)
    except Exception:
        pass

    print("  [база] материалов не найдено, генерирую из общих знаний")
    return ""

