def generate_post(topic: str, platform: str, notebook_id: str = None) -> str:
    platform_name = PLATFORMS[platform]

    platform_notes = {
        "vk_personal": "Пост для личной страницы. Длина — средняя (400–700 слов). Можно быть чуть более личным в наблюдениях.",
        "vk_group": "Пост для тематической группы. Длина — средняя или длинная (500–900 слов). Больше структуры и подзаголовков.",
        "telegram": "Пост для Telegram-канала. Длина — короткая или средняя (200–400 слов). Плотнее, без лишних слов.",
        "dzen": "Статья для Яндекс Дзен. Длина — длинная (800–1200 слов). Обязательно заголовок и подзаголовки. SEO-дружественный стиль.",
    }

    knowledge_context = search_knowledge(topic, notebook_id=notebook_id)
    knowledge_block = f"\n\nИспользуй эти материалы как основу для поста (факты, цитаты, конкретные детали):\n{knowledge_context}\n" if knowledge_context else ""

    user_prompt = f"""Напиши пост для площадки: {platform_name}.
{platform_notes[platform]}

Тема: «{topic}»
{knowledge_block}
Структура ответа:
1. Первая строка — цепляющий заголовок поста (без символов #, *, без кавычек). Заголовок должен интриговать, намекать на содержание, вызывать желание читать дальше. После заголовка — пустая строка.
2. Текст поста.
3. Хэштеги (4–5 штук) на отдельной строке в конце."""

    banned_phrases = [
        "сегодня поговорим", "давайте разберёмся", "давайте поговорим",
        "в мире психологии", "всем привет", "магия", "волшебство",
    ]

    def clean_markdown(text: str) -> str:
        import re
        lines = text.strip().split('\n')
        # Первую строку (заголовок) не трогаем — убираем только лидирующий # если есть
        if lines:
            lines[0] = re.sub(r'^#{1,6}\s+', '', lines[0]).strip()
        body = '\n'.join(lines[1:])
        body = re.sub(r'^#{1,6}\s+', '', body, flags=re.MULTILINE)  # # в теле
        body = re.sub(r'\*\*(.+?)\*\*', r'\1', body)                 # **жирный**
        body = re.sub(r'\*(.+?)\*', r'\1', body)                     # *курсив*
        body = re.sub(r'^[-*]\s+', '', body, flags=re.MULTILINE)     # маркеры списков
        body = re.sub(r'^\d+\.\s+', '', body, flags=re.MULTILINE)    # нумерация
        body = re.sub(r'\n{3,}', '\n\n', body)                       # лишние пустые строки
        return (lines[0] + '\n' + body).strip()

    for attempt in range(3):
        response = client.chat.completions.create(
            model="gpt-4o",
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": user_prompt},
            ],
            temperature=0.85 + attempt * 0.05,
        )
        text = clean_markdown(response.choices[0].message.content)
        if not any(phrase in text.lower() for phrase in banned_phrases):
            return text

    return text


